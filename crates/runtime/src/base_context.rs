//! Base context inspection: the system text, tools and model settings a run starts with.
//!
//! [`compose_system_sections`] is the single source of the initial system message:
//! the agent loop joins its sections into the provider request, and
//! [`crate::AgentRuntime::preview_base_context`] returns the same sections with their
//! provenance, so the inspector never drifts from what runs actually receive.

