#!/usr/bin/env node
// Collects the per-fixture results of one cutover run into the evidence
// directory: summary.json (machine readable) and summary.md (for the PR).
// Exit code: 0 = every check passed, 1 = a check failed, 2 = no failure but
// something is unverified/todo (NOT success).
import fs from "node:fs";
import path from "node:path";

const args = Object.fromEntries(
  process.argv.slice(2).reduce((acc, a, i, all) => (a.startsWith("--") ? [...acc, [a.slice(2), all[i + 1]]] : acc), []),
);
const meta = JSON.parse(fs.readFileSync(args.meta, "utf8"));
const out = args.out;
const fixtures = [];
for (const entry of meta.fixtures) {
  const dir = path.join(entry.root, "driver");
  const read = (name) => {
    try {
      return JSON.parse(fs.readFileSync(path.join(dir, name), "utf8"));
    } catch {
      return null;
    }
  };
  const verify = read(`verify-results.json`);
  const gen = read(`gen-results.json`);
  fixtures.push({
    fixture: entry.fixture,
    root: entry.root,
    genAttempts: entry.genAttempts,
    genSummary: gen?.summary ?? null,
    genFailures: (gen?.items ?? []).filter((i) => i.status === "fail"),
    verifySummary: verify?.summary ?? null,
    items: verify?.items ?? [],
    verifyRan: !!verify,
  });
}
// Known issues that the unmodified old build shows in the same way (so they are not introduced by
// PR C and are out of its scope). Display only: the status and the exit code are not affected.
const BASELINE_SHARED = new Set([
  "existing-thread:history-restored",
  "attachment:referenced-in-restored-history",
  "restart:new-restart-completes",
]);
const baselineShared = (i) => i.status === "fail" && BASELINE_SHARED.has(i.id);
const total = { pass: 0, fail: 0, unverified: 0, todo: 0 };
let incompleteRun = false;
for (const f of fixtures) {
  if (!f.verifyRan) incompleteRun = true;
  for (const [k, v] of Object.entries(f.verifySummary ?? {})) total[k] += v;
  total.fail += f.genFailures.length;
}
const baselineSharedFails = fixtures.flatMap((f) => f.items.filter(baselineShared).map((i) => i.id));
const status = total.fail > 0 || incompleteRun ? "FAIL" : total.unverified + total.todo > 0 ? "INCOMPLETE" : "PASS";
const summary = { status, total, baselineSharedFails, newFailsOutsideBaseline: total.fail - baselineSharedFails.length, ...meta, fixtures };
fs.writeFileSync(path.join(out, "summary.json"), JSON.stringify(summary, null, 2));

const md = [];
md.push(`# PR 20 cutover verification: ${status}`);
md.push("");
md.push(`- old build: \`${meta.old.sha}\` core sha256 \`${meta.old.coreSha256}\` evorch sha256 \`${meta.old.evorchSha256}\``);
md.push(`- new build: \`${meta.new.sha}\` core sha256 \`${meta.new.coreSha256}\` evorch sha256 \`${meta.new.evorchSha256}\``);
md.push(`- project approved by the old core while generating (--approve): ${meta.approveProject}`);
md.push(`- guard bundle (old): ${JSON.stringify(meta.guard?.old)}`);
md.push(`- guard bundle (new): ${JSON.stringify(meta.guard?.new)}`);
for (const label of ["old", "new"]) {
  const s = meta.sourceFiles?.[label];
  md.push(`- source delivery of the ${label} build left unchanged (files hashed before and after the run): ${s ? s.unchanged : "not recorded"} ${JSON.stringify(s?.after ?? {})}`);
}
md.push(`- environment: ${JSON.stringify(meta.environment)}`);
md.push(`- totals: ${JSON.stringify(total)} (only \`pass\` is success; \`unverified\`/\`todo\` are not)`);
md.push(`- fails marked baseline-shared (known, out of scope; the unmodified old build fails them too; they still count as fail and keep the exit code): ${baselineSharedFails.length} of ${total.fail} fail(s)${baselineSharedFails.length ? ` (${baselineSharedFails.map((i) => `\`${i}\``).join(", ")})` : ""}`);
md.push(`- fixtures were generated by the old build only; no database, snapshot or owner row was edited by hand`);
md.push("");
for (const f of fixtures) {
  md.push(`## fixture \`${f.fixture}\` (work root \`${f.root}\`, generation attempts ${f.genAttempts})`);
  if (!f.verifyRan) md.push("**the verification phase did not run to completion**");
  for (const g of f.genFailures) md.push(`- FAIL (generation) ${g.id}: ${g.detail}`);
  for (const i of f.items) md.push(`- ${i.status.toUpperCase()}${baselineShared(i) ? " (baseline-shared, known, out of scope)" : ""} \`${i.id}\`${i.detail ? `: ${i.detail}` : ""}`);
  md.push("");
}
fs.writeFileSync(path.join(out, "summary.md"), md.join("\n"));
console.log(`${status} ${JSON.stringify(total)}${baselineSharedFails.length ? ` baseline-shared fails: ${baselineSharedFails.length}` : ""}`);
process.exit(status === "PASS" ? 0 : status === "FAIL" ? 1 : 2);
